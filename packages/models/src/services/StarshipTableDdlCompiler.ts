import type { StarshipDatasetColumn } from '@starships/protocol';
import { quoteIdent, constraintName } from '@/helpers/starship-tables/identifiers';

/**
 * Compiles authored Table column definitions into Postgres DDL.
 *
 * A Table lives at `db_<starshipId>."<physicalTable>"` and always carries four
 * hidden columns:
 *   __id         text PRIMARY KEY        (app-generated nanoid surrogate key)
 *   __row_key    text [UNIQUE]           (mirrors the logical primaryKey value; upsert target)
 *   __created_at timestamptz             (app-maintained)
 *   __updated_at timestamptz             (app-maintained)
 *
 * Formula columns are dropped from the product, so `type: 'formula'` columns are
 * ignored here. Pattern constraints are enforced app-side (JS regex flavor),
 * not as Postgres CHECKs.
 */

/** Thrown when an ALTER diff would require a destructive rebuild (v1 rejects these). */
export class TableSchemaChangeError extends Error {
  readonly code = 'TABLE_SCHEMA_CHANGE_UNSUPPORTED';
  constructor(message: string) {
    super(message);
    this.name = 'TableSchemaChangeError';
  }
}

export const HIDDEN_COLUMNS = ['__id', '__row_key', '__created_at', '__updated_at'] as const;

type Col = StarshipDatasetColumn;

const isFormula = (c: Col): boolean => c.type === 'formula';
const isAutoincrement = (c: Col): boolean => Boolean(c.constraints?.autoincrement) && (c.type ?? 'string') === 'number';

/** Logical column type → Postgres type. */
export function pgTypeFor(col: Col): string {
  const type = col.type ?? 'string';
  switch (type) {
    case 'number':
      return col.format === 'currency' || col.format === 'percentage' ? 'numeric' : 'double precision';
    case 'boolean':
      return 'boolean';
    case 'date':
      return 'date';
    case 'datetime':
      return 'timestamptz';
    case 'json':
      return 'jsonb';
    case 'enum':
    case 'reference':
    case 'string':
    default: {
      const max = col.constraints?.maxLength;
      return typeof max === 'number' && max > 0 ? `varchar(${Math.floor(max)})` : 'text';
    }
  }
}

/** Render a value as a typed SQL literal for DEFAULT / CHECK. Returns null to skip. */
function literal(value: unknown, type: string): string | null {
  if (value === null || value === undefined) return null;
  switch (type) {
    case 'number': {
      const n = typeof value === 'number' ? value : Number(value);
      return Number.isFinite(n) ? String(n) : null;
    }
    case 'boolean':
      return value === true || value === 'true' || value === 1 ? 'true' : 'false';
    case 'json': {
      const json = typeof value === 'string' ? value : JSON.stringify(value);
      return `'${json.replace(/'/g, "''")}'::jsonb`;
    }
    default:
      return `'${String(value).replace(/'/g, "''")}'`;
  }
}

/** Build the named CHECK constraints for a column (enum / numeric / length bounds). */
function checkConstraints(physicalTable: string, col: Col): Array<{ name: string; expr: string }> {
  const out: Array<{ name: string; expr: string }> = [];
  const type = col.type ?? 'string';
  const qcol = quoteIdent(col.name);

  if (type === 'enum' && Array.isArray(col.enum?.options) && col.enum.options.length > 0) {
    const list = col.enum.options.map((o) => `'${String(o).replace(/'/g, "''")}'`).join(', ');
    out.push({ name: constraintName(physicalTable, col.name, 'enum'), expr: `${qcol} IN (${list})` });
  }
  if (type === 'number') {
    if (typeof col.constraints?.min === 'number') {
      out.push({ name: constraintName(physicalTable, col.name, 'min'), expr: `${qcol} >= ${col.constraints.min}` });
    }
    if (typeof col.constraints?.max === 'number') {
      out.push({ name: constraintName(physicalTable, col.name, 'max'), expr: `${qcol} <= ${col.constraints.max}` });
    }
  }
  if (type === 'string' || type === 'enum' || type === 'reference') {
    if (typeof col.constraints?.minLength === 'number') {
      out.push({ name: constraintName(physicalTable, col.name, 'minlen'), expr: `char_length(${qcol}) >= ${col.constraints.minLength}` });
    }
    if (typeof col.constraints?.maxLength === 'number') {
      out.push({ name: constraintName(physicalTable, col.name, 'maxlen'), expr: `char_length(${qcol}) <= ${col.constraints.maxLength}` });
    }
  }
  return out;
}

/** Inline column definition fragment (without CHECKs, which are added as table-level constraints). */
function columnDefinition(col: Col): string {
  const qcol = quoteIdent(col.name);
  if (isAutoincrement(col)) {
    return `${qcol} bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL`;
  }
  const parts = [qcol, pgTypeFor(col)];
  const notNull = Boolean(col.constraints?.required) && !col.constraints?.nullable;
  if (notNull) parts.push('NOT NULL');
  const def = literal(col.constraints?.default, col.type ?? 'string');
  if (def !== null) parts.push(`DEFAULT ${def}`);
  return parts.join(' ');
}

export interface CompileTableArgs {
  /** Fully quoted, schema-qualified table reference, e.g. `"db_x"."customers"`. */
  table: string;
  /** Raw physical table name (for deterministic constraint/index names). */
  physicalTable: string;
  columns: Col[];
  primaryKey?: string | null;
}

/** Statements to create a Table (CREATE TABLE + indexes). Run inside a transaction. */
export function compileCreateTable(args: CompileTableArgs): string[] {
  const userCols = (args.columns ?? []).filter((c) => c && c.name && !isFormula(c));
  const hasPk = typeof args.primaryKey === 'string' && args.primaryKey.length > 0;

  const lines: string[] = [
    `${quoteIdent('__id')} text PRIMARY KEY`,
    `${quoteIdent('__row_key')} text${hasPk ? ' UNIQUE' : ''}`,
    `${quoteIdent('__created_at')} timestamptz NOT NULL DEFAULT now()`,
    `${quoteIdent('__updated_at')} timestamptz NOT NULL DEFAULT now()`,
  ];

  const checks: string[] = [];
  for (const col of userCols) {
    lines.push(columnDefinition(col));
    for (const c of checkConstraints(args.physicalTable, col)) {
      checks.push(`CONSTRAINT ${quoteIdent(c.name)} CHECK (${c.expr})`);
    }
  }

  const body = [...lines, ...checks].join(',\n  ');
  const stmts = [`CREATE TABLE ${args.table} (\n  ${body}\n)`];

  // Pagination index mirrors the JSONB era's (created_at, id) ordering.
  const idxName = constraintName(args.physicalTable, '__created', 'idx');
  stmts.push(`CREATE INDEX ${quoteIdent(idxName)} ON ${args.table} (${quoteIdent('__created_at')}, ${quoteIdent('__id')})`);
  return stmts;
}

export interface CompileAlterArgs extends CompileTableArgs {
  oldColumns: Col[];
}

/**
 * Diff old vs new columns and emit ALTER statements. Safe changes: add/drop
 * column, nullability, default, and enum/bound CHECK changes. Anything that
 * needs a destructive rebuild (logical type change, toggling autoincrement)
 * throws TableSchemaChangeError so the route can reject with a 400.
 */
export function compileAlterTable(args: CompileAlterArgs): string[] {
  const oldByName = new Map(args.oldColumns.filter((c) => c && c.name && !isFormula(c)).map((c) => [c.name, c]));
  const newByName = new Map(args.columns.filter((c) => c && c.name && !isFormula(c)).map((c) => [c.name, c]));
  const stmts: string[] = [];
  const t = args.table;

  // Dropped columns
  for (const name of oldByName.keys()) {
    if (!newByName.has(name)) stmts.push(`ALTER TABLE ${t} DROP COLUMN ${quoteIdent(name)}`);
  }

  for (const [name, next] of newByName) {
    const prev = oldByName.get(name);

    if (!prev) {
      // Added column. NOT NULL only when a default is present (greenfield-safe).
      const def = literal(next.constraints?.default, next.type ?? 'string');
      const wantsNotNull = Boolean(next.constraints?.required) && !next.constraints?.nullable;
      const colDef = isAutoincrement(next)
        ? `${quoteIdent(name)} bigint GENERATED BY DEFAULT AS IDENTITY`
        : `${quoteIdent(name)} ${pgTypeFor(next)}${wantsNotNull && def !== null ? ' NOT NULL' : ''}${def !== null ? ` DEFAULT ${def}` : ''}`;
      stmts.push(`ALTER TABLE ${t} ADD COLUMN ${colDef}`);
      for (const c of checkConstraints(args.physicalTable, next)) {
        stmts.push(`ALTER TABLE ${t} ADD CONSTRAINT ${quoteIdent(c.name)} CHECK (${c.expr})`);
      }
      continue;
    }

    // Reject destructive shape changes.
    if (pgTypeFor(prev) !== pgTypeFor(next)) {
      throw new TableSchemaChangeError(
        `Column "${name}" type change (${pgTypeFor(prev)} -> ${pgTypeFor(next)}) requires recreating the Table.`
      );
    }
    if (isAutoincrement(prev) !== isAutoincrement(next)) {
      throw new TableSchemaChangeError(`Column "${name}" autoincrement change requires recreating the Table.`);
    }

    // Nullability
    const prevNotNull = Boolean(prev.constraints?.required) && !prev.constraints?.nullable;
    const nextNotNull = Boolean(next.constraints?.required) && !next.constraints?.nullable;
    if (prevNotNull !== nextNotNull) {
      stmts.push(`ALTER TABLE ${t} ALTER COLUMN ${quoteIdent(name)} ${nextNotNull ? 'SET' : 'DROP'} NOT NULL`);
    }

    // Default
    const prevDef = literal(prev.constraints?.default, prev.type ?? 'string');
    const nextDef = literal(next.constraints?.default, next.type ?? 'string');
    if (prevDef !== nextDef) {
      stmts.push(
        `ALTER TABLE ${t} ALTER COLUMN ${quoteIdent(name)} ${nextDef === null ? 'DROP DEFAULT' : `SET DEFAULT ${nextDef}`}`
      );
    }

    // CHECK constraints (enum/bounds): replace any that changed.
    const prevChecks = new Map(checkConstraints(args.physicalTable, prev).map((c) => [c.name, c.expr]));
    const nextChecks = new Map(checkConstraints(args.physicalTable, next).map((c) => [c.name, c.expr]));
    for (const [cname] of prevChecks) {
      if (!nextChecks.has(cname) || nextChecks.get(cname) !== prevChecks.get(cname)) {
        stmts.push(`ALTER TABLE ${t} DROP CONSTRAINT IF EXISTS ${quoteIdent(cname)}`);
      }
    }
    for (const [cname, expr] of nextChecks) {
      if (!prevChecks.has(cname) || prevChecks.get(cname) !== expr) {
        stmts.push(`ALTER TABLE ${t} ADD CONSTRAINT ${quoteIdent(cname)} CHECK (${expr})`);
      }
    }
  }

  return stmts;
}
