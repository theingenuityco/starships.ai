/**
 * Database Agent Types
 *
 * Database-specific agent interfaces and API contract types.
 * Imports workflow and memory types from @starships/autopilot to avoid duplication.
 */

import type { AgentParams } from './llm';
import type { Blueprint } from './workflow';

// ============================================================================
// DATABASE AGENT INTERFACE
// ============================================================================

/**
 * Database Agent interface - core API contract type
 * Extends AgentParams to be a superset with additional database/marketplace fields
 */

export type AgentParamsWithoutMetadata = Omit<AgentParams, 'metadata' | 'tools'>;

export interface AgentModel extends AgentParamsWithoutMetadata {
  // Core database fields
  id: string;
  slug: string;
  /**
   * Human-readable role label for the agent (e.g. "Customer Support Agent").
   * This is required and is used across UI/marketplace and seeded tooling.
   */
  role: string;
  createdAt: string;
  updatedAt: string;
  // Optional categorization (for organizing agents in UI/marketplace)
  category?: string;
  // Starship ownership (FK)
  starshipId: string;
  // Optional example prompts surfaced on agents
  previewPrompts?: string[];
  // Versioning fields
  version: string; // Semantic version (e.g., '1.0.2')

  /** Inert legacy agent blueprint (DAG engine removed; column dropped separately). */
  blueprint?: Blueprint;

  /**
   * Optional avatar image for the agent, stored as an Attachment (S3-backed).
   * This is auth-scoped via starship access and served through the attachments endpoints.
   */
  avatarAttachmentId?: string;

  /**
   * Optional agent-authored avatar prompt used to guide avatar generation.
   * Typically generated by asking the agent to "look into a mirror and reply with what it sees".
   */
  avatarPrompt?: string;

  /**
   * Optional profile image attachments for the agent, stored as Attachments (S3-backed).
   * These are auth-scoped via starship access and served through the attachments endpoints.
   */
  problemStatementsAttachmentId?: string;
  capabilitiesAttachmentId?: string;
  tryThesePromptsAttachmentId?: string;
}

// ============================================================================
// AGENT REQUEST/RESPONSE TYPES
// ============================================================================

/**
 * Request to create a new agent
 */
export type CreateAgentRequest = AgentParamsWithoutMetadata & {
  /**
   * Human-readable role label for the agent (required).
   */
  role: string;
  // Optional categorization (for organizing agents in UI/marketplace)
  category?: string;
  // Optional prompts
  previewPrompts?: string[];
  // Versioning fields
  version?: string;
  /** Inert legacy agent blueprint (DAG engine removed). */
  blueprint?: Blueprint;
};

/**
 * Request to update an agent
 */
export interface UpdateAgentRequest extends Partial<Omit<AgentParamsWithoutMetadata, 'reasoning'>> {
  /**
   * Slugs are server-generated and not directly editable.
   */
  slug?: never;
  /**
   * Optional role update.
   */
  role?: string;
  // Optional categorization (for organizing agents in UI/marketplace)
  category?: string;
  previewPrompts?: string[];
  /**
   * Optional structured reasoning config.
   * Allow `null` to explicitly clear an existing config.
   */
  reasoning?: AgentParamsWithoutMetadata['reasoning'] | null;
  version?: string;
  /** Inert legacy agent blueprint (DAG engine removed). */
  blueprint?: Blueprint;

  /**
   * Optional avatar image for the agent, stored as an Attachment (S3-backed).
   * Generally set by server-side avatar generation flows.
   */
  avatarAttachmentId?: string;

  /**
   * Optional agent-authored avatar prompt used to guide avatar generation.
   */
  avatarPrompt?: string;

  /**
   * Optional profile image attachments for the agent, stored as Attachments (S3-backed).
   * Generally set by server-side profile image generation flows.
   */
  problemStatementsAttachmentId?: string;
  capabilitiesAttachmentId?: string;
  tryThesePromptsAttachmentId?: string;
}

