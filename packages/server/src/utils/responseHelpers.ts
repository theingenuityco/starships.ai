/**
 * Response helpers for consistent API responses following OpenAPI standards
 */

import { ErrorUtils } from '@starships/errors';
import type { ApiErrorResponse, ApiResponse, ApiResponseMeta, StandardErrorCode } from '@starships/protocol';
import type { Response } from 'express';

/**
 * Send standardized success response
 */
export function sendSuccess<T>(res: Response, data: T, statusCode: number = 200, meta?: ApiResponseMeta): void {
  const response: ApiResponse<T> = { data };
  if (meta) {
    response.meta = meta;
  }
  res.status(statusCode).json(response);
}

/**
 * Send standardized error response
 */
export function sendError(
  res: Response,
  code: StandardErrorCode,
  message: string,
  statusCode: number = 500,
  details?: Record<string, any>
): void {
  const response: ApiErrorResponse = {
    error: {
      code,
      message,
      ...(details && { details }),
    },
  };
  res.status(statusCode).json(response);
}

/**
 * Create pagination metadata
 */
export function createPaginationMeta(page: number, limit: number, total: number): ApiResponseMeta {
  return {
    pagination: {
      page,
      limit,
      total,
      has_next: page * limit < total,
      has_prev: page > 1,
    },
  };
}

/**
 * Validate pagination parameters
 */
export function validatePagination(
  page?: string,
  limit?: string
): {
  page: number;
  limit: number;
  error?: { code: StandardErrorCode; message: string };
} {
  const pageNum = page ? parseInt(page, 10) : 1;
  const limitNum = limit ? parseInt(limit, 10) : 50;

  if (isNaN(pageNum) || pageNum < 1) {
    return {
      page: 1,
      limit: 50,
      error: {
        code: 'VALIDATION_ERROR',
        message: 'Page must be a positive integer',
      },
    };
  }

  if (isNaN(limitNum) || limitNum < 1 || limitNum > 200) {
    return {
      page: pageNum,
      limit: 50,
      error: {
        code: 'VALIDATION_ERROR',
        message: 'Limit must be between 1 and 200',
      },
    };
  }

  return { page: pageNum, limit: limitNum };
}

/**
 * ID validation helper - validates the new ID format (base-36 encoded)
 * Replaces the old UUID validation to support the new ID generation method
 */
export function validateId(
  id: string,
  fieldName: string
): {
  isValid: boolean;
  error?: { code: StandardErrorCode; message: string; details?: any };
} {
  if (!id || typeof id !== 'string') {
    return {
      isValid: false,
      error: {
        code: 'MISSING_REQUIRED_FIELD',
        message: `${fieldName} is required and must be a string`,
        details: { field: fieldName },
      },
    };
  }

  // ID format: nanoid generated string (URL-safe alphabet)
  // Generated by: nanoid() which uses A-Za-z0-9_- characters
  // Should be URL-safe, typically 10-30 characters long
  const idRegex = /^[a-z0-9_-]{10,30}$/i;
  if (!idRegex.test(id)) {
    return {
      isValid: false,
      error: {
        code: 'INVALID_FORMAT',
        message: `${fieldName} must be a valid ID format`,
        details: { field: fieldName, provided: id },
      },
    };
  }

  return { isValid: true };
}

/**
 * Flexible ID or slug validation helper
 * Supports both new ID format and URL-safe slugs (for starships, etc.)
 */
export function validateIdOrSlug(
  value: string,
  fieldName: string
): {
  isValid: boolean;
  error?: { code: StandardErrorCode; message: string; details?: any };
} {
  if (!value || typeof value !== 'string') {
    return {
      isValid: false,
      error: {
        code: 'MISSING_REQUIRED_FIELD',
        message: `${fieldName} is required and must be a string`,
        details: { field: fieldName },
      },
    };
  }

  // Accept either:
  // 1. ID format: nanoid generated string (URL-safe alphabet, 10-30 chars)
  // 2. URL-safe slug format: lowercase letters, numbers, hyphens (1-100 chars)
  const idRegex = /^[a-z0-9_-]{10,30}$/i;
  const slugRegex = /^[a-z0-9-]{1,100}$/i;

  if (!idRegex.test(value) && !slugRegex.test(value)) {
    return {
      isValid: false,
      error: {
        code: 'INVALID_FORMAT',
        message: `${fieldName} must be a valid ID or slug format`,
        details: { field: fieldName, provided: value },
      },
    };
  }

  return { isValid: true };
}

/**
 * @deprecated Use validateId instead. This function is kept for backward compatibility.
 * UUID validation helper - kept for legacy support
 */
export function validateUUID(
  id: string,
  fieldName: string
): {
  isValid: boolean;
  error?: { code: StandardErrorCode; message: string; details?: any };
} {
  // For now, delegate to the new validateId function
  // This maintains backward compatibility while supporting the new ID format
  return validateId(id, fieldName);
}

/**
 * Handle common errors and convert to standardized responses
 */
export function handleCommonError(error: any, res: Response, context: string): boolean {
  console.error(`Error in ${context}:`, error);

  // Check if it's already a structured error from @starships/errors
  if (ErrorUtils.isApplicationError(error)) {
    const response = error.toResponse();
    sendError(
      res,
      response.code as StandardErrorCode,
      response.message,
      response.statusCode,
      response.details as Record<string, any> | undefined
    );
    return true;
  }

  // Handle known error types by name for backward compatibility
  if (error.name === 'ValidationError' || error.constructor.name === 'ValidationError') {
    sendError(res, 'VALIDATION_ERROR', error.message, 400, {
      field: error.field,
    });
    return true;
  }

  if (error.name === 'NotFoundError' || error.constructor.name === 'NotFoundError') {
    sendError(res, 'RESOURCE_NOT_FOUND', error.message, 404, {
      entityType: error.entityType,
      entityId: error.entityId,
    });
    return true;
  }

  if (error.name === 'ConflictError' || error.constructor.name === 'ConflictError') {
    sendError(res, 'RESOURCE_CONFLICT', error.message, 409, {
      conflictType: error.conflictType,
    });
    return true;
  }

  // Return false if not handled - caller should handle generic error
  return false;
}

/**
 * Safe error message extraction
 */
export function getErrorMessage(error: unknown): string {
  if (error instanceof Error) {
    return error.message;
  }
  return String(error);
}
