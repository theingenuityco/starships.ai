import { ToolEntity } from '@/entities/ToolEntity';
import { fromDatabase, fromDatabaseArray, toDatabase, toEntityInstance } from '@/helpers/serialization-helper';
import { BaseRepository } from '@/repositories/BaseRepository';
import type {
  ToolModel,
  CreateToolRequest,
  UpdateToolRequest,
  ToolSearchParams,
} from '@starships/protocol';
import { generateUniqueSlugIncremental } from '@/utils/slugGenerator';
import { generateSlug } from '@/helpers/slugUtils';
import { computeToolContentHash } from '@/utils/contentHash';
import type { PostgresConnection } from '@/helpers/database';

export class ToolRepository extends BaseRepository {
  constructor(connection?: PostgresConnection) {
    super('ToolRepository', connection);
  }

  private async toolSlugExistsOnStarship(starshipId: string, slug: string, excludeId?: string): Promise<boolean> {
    const connection = this.getConnection();
    if (excludeId) {
      const row = await connection.queryOne<{ id: string }>('SELECT id FROM tools WHERE starship_id = $1 AND slug = $2 AND id <> $3', [
        starshipId,
        slug,
        excludeId,
      ]);
      return !!row?.id;
    }
    const row = await connection.queryOne<{ id: string }>('SELECT id FROM tools WHERE starship_id = $1 AND slug = $2', [starshipId, slug]);
    return !!row?.id;
  }

  /**
   * Create a tool instance for a starship via import flows.
   *
   * NOTE: Tool slugs are always generated by the server (never preserved from import payloads).
   */
  async createImported(data: CreateToolRequest & { slug?: string }, starshipId: string): Promise<ToolModel> {
    return this.executeWithErrorHandling(
      async () => {
        const now = new Date().toISOString();

        // Slugs are always generated by the server.
        // Instance slugs use incremental suffixes and are unique PER starship.
        const baseFromName = generateSlug((data.name || 'tool').toString()) || 'tool';
        const slug = await generateUniqueSlugIncremental(
          baseFromName,
          async (candidate) => await this.toolSlugExistsOnStarship(starshipId, candidate),
          { fallbackBase: 'tool', maxLength: 100 }
        );

        // Explicitly omit configuration from imports by default; callers can pass it if desired.
        // eslint-disable-next-line @typescript-eslint/no-unused-vars
        const { configuration: _configuration, ...rest } = data;

        const toolProps = {
          // Core ToolParams fields
          name: rest.name,
          description: rest.description,
          parameters: rest.parameters,
          transforms: rest.transforms,
          mutations: rest.mutations,
          condition: rest.condition,

          // Tool instance fields
          slug,
          configuration: undefined,
          isEnabled: rest.isEnabled ?? true,
          status: rest.status || 'active',
          contentHash: computeToolContentHash({
            name: rest.name,
            description: rest.description,
            parameters: rest.parameters,
            transforms: rest.transforms,
            mutations: rest.mutations,
            condition: rest.condition,
            isEnabled: rest.isEnabled ?? true,
            status: rest.status || 'active',
          }),

          // Relationship field
          starshipId: starshipId,

          // Versioning fields
          version: rest.version || '1.0.0',

          // Database-specific fields
          createdAt: now,
          updatedAt: now,
        };

        await ToolEntity.validate(toolProps, 'create');

        const toolEntity = toEntityInstance(ToolEntity, toolProps);
        const databaseFormat = toDatabase(toolEntity);
        const result = await this.createEntity<Record<string, unknown>>('tools', databaseFormat);

        return fromDatabase(ToolEntity, result);
      },
      'createImported',
      'Tool'
    );
  }

  async findAll(): Promise<ToolModel[]> {
    return this.executeWithErrorHandling(
      async () => {
        const result = await super.findAllEntities<Record<string, unknown>>('tools', 'created_at DESC');
        return fromDatabaseArray(ToolEntity, result);
      },
      'findAll',
      'Tool'
    );
  }

  async findById(id: string): Promise<ToolModel | null> {
    return this.executeWithErrorHandling(
      async () => {
        const result = await super.findEntityById<Record<string, unknown>>('tools', id);
        if (!result) return null;

        const tool = fromDatabase(ToolEntity, result) as ToolModel;

        return tool;
      },
      'findById',
      'Tool',
      id
    );
  }

  async findBySlug(slug: string): Promise<ToolModel | null> {
    return this.executeWithErrorHandling(
      async () => {
        const connection = this.getConnection();
        const result = await connection.queryOne<Record<string, unknown>>('SELECT * FROM tools WHERE slug = $1', [slug]);
        return result ? fromDatabase(ToolEntity, result) : null;
      },
      'findBySlug',
      'Tool',
      slug
    );
  }

  async findByStarship(starshipId: string): Promise<ToolModel[]> {
    return this.executeWithErrorHandling(
      async () => {
        const connection = this.getConnection();
        const result = await connection.query<Record<string, unknown>>(
          'SELECT * FROM tools WHERE starship_id = $1 ORDER BY created_at DESC',
          [starshipId]
        );
        const tools = fromDatabaseArray(ToolEntity, result) as ToolModel[];

        return tools;
      },
      'findByStarship',
      'Tool'
    );
  }

  async findBySlugAndStarship(slug: string, starshipId: string): Promise<ToolModel | null> {
    return this.executeWithErrorHandling(
      async () => {
        const connection = this.getConnection();
        const result = await connection.queryOne<Record<string, unknown>>('SELECT * FROM tools WHERE slug = $1 AND starship_id = $2', [
          slug,
          starshipId,
        ]);
        if (!result) return null;

        const tool = fromDatabase(ToolEntity, result) as ToolModel;

        return tool;
      },
      'findBySlugAndStarship',
      'Tool',
      `${slug}@${starshipId}`
    );
  }

  async findBySlugs(slugs: string[], starshipId: string): Promise<ToolModel[]> {
    return this.executeWithErrorHandling(
      async () => {
        const connection = this.getConnection();
        const result = await connection.query<Record<string, unknown>>(
          'SELECT * FROM tools WHERE slug = ANY($1) AND starship_id = $2 ORDER BY created_at DESC',
          [slugs, starshipId]
        );
        return fromDatabaseArray(ToolEntity, result);
      },
      'findBySlugs',
      'Tool'
    );
  }

  async search(params: ToolSearchParams): Promise<ToolModel[]> {
    return this.executeWithErrorHandling(
      async () => {
        const connection = this.getConnection();
        let query = 'SELECT * FROM tools WHERE 1=1';
        const sqlParams: unknown[] = [];
        let paramIndex = 1;

        if (params.isEnabled !== undefined) {
          query += ` AND is_enabled = $${paramIndex++}`;
          sqlParams.push(params.isEnabled);
        }

        if (params.status !== undefined) {
          query += ` AND status = $${paramIndex++}`;
          sqlParams.push(params.status);
        }

        if (params.query) {
          query += ` AND (LOWER(name) LIKE LOWER($${paramIndex++}) OR LOWER(description) LIKE LOWER($${paramIndex++}))`;
          sqlParams.push(`%${params.query}%`);
          sqlParams.push(`%${params.query}%`);
        }

        query += ' ORDER BY created_at DESC';

        const result = await connection.query<Record<string, unknown>>(query, sqlParams);
        return fromDatabaseArray(ToolEntity, result);
      },
      'search',
      'Tool'
    );
  }

  async create(data: CreateToolRequest, starshipId: string): Promise<ToolModel> {
    return this.executeWithErrorHandling(
      async () => {
        const now = new Date().toISOString();

        // Slugs are always generated by the server.
        // Instance slugs use incremental suffixes and are unique PER starship.
        const baseFromName = generateSlug((data.name || 'tool').toString()) || 'tool';
        const slug = await generateUniqueSlugIncremental(
          baseFromName,
          async (candidate) => await this.toolSlugExistsOnStarship(starshipId, candidate),
          { fallbackBase: 'tool', maxLength: 100 }
        );

        // Create tool properties including starship relationship
        const toolProps = {
          // Core ToolParams fields
          name: data.name,
          description: data.description,
          parameters: data.parameters,
          transforms: data.transforms,
          mutations: data.mutations,
          condition: data.condition,

          // Tool instance fields
          slug,
          configuration: data.configuration,
          isEnabled: data.isEnabled ?? true,
          status: data.status || 'active',
          contentHash: computeToolContentHash({
            name: data.name,
            description: data.description,
            parameters: data.parameters,
            transforms: data.transforms,
            mutations: data.mutations,
            condition: data.condition,
            isEnabled: data.isEnabled ?? true,
            status: data.status || 'active',
          }),

          // Relationship field
          starshipId: starshipId,

          // Versioning fields
          version: data.version || '1.0.0',
          ...(data.requiredConnectorProviders ? { requiredConnectorProviders: data.requiredConnectorProviders } : {}),

          // Database-specific fields
          createdAt: now,
          updatedAt: now,
        };

        // Validate using entity
        await ToolEntity.validate(toolProps, 'create');

        // Create entity instance from plain object, then serialize
        const toolEntity = toEntityInstance(ToolEntity, toolProps);
        const databaseFormat = toDatabase(toolEntity);
        const result = await this.createEntity<Record<string, unknown>>('tools', databaseFormat);

        return fromDatabase(ToolEntity, result);
      },
      'create',
      'Tool'
    );
  }

  async update(id: string, updates: UpdateToolRequest): Promise<ToolModel | null> {
    return this.executeWithErrorHandling(
      async () => {
        const existing = await this.findById(id);
        if (!existing) return null;

        const updateProps: Partial<ToolModel> = {
          ...(updates as Partial<ToolModel>),
          updatedAt: new Date().toISOString(),
        };

        // Auto-regenerate slug on name updates
        if (updates.name !== undefined && updates.name !== null) {
          const baseFromName = generateSlug(String(updates.name)) || 'tool';
          updateProps.slug = await generateUniqueSlugIncremental(
            baseFromName,
            async (candidate) => await this.toolSlugExistsOnStarship(existing.starshipId, candidate, existing.id),
            { fallbackBase: 'tool', maxLength: 100 }
          );
        }

        // Validate updates using entity rules (e.g., description max length).
        await ToolEntity.validate(updateProps, 'update');

        // Convert entity updates to database format
        const mergedForHash = {
          name: updates.name !== undefined ? updates.name : existing.name,
          description: updates.description !== undefined ? updates.description : existing.description,
          parameters: updates.parameters !== undefined ? updates.parameters : existing.parameters,
          transforms: updates.transforms !== undefined ? updates.transforms : existing.transforms,
          mutations: updates.mutations !== undefined ? updates.mutations : existing.mutations,
          condition: updates.condition !== undefined ? updates.condition : existing.condition,
          isEnabled: updates.isEnabled !== undefined ? updates.isEnabled : existing.isEnabled,
          status: updates.status !== undefined ? updates.status : existing.status,
        };
        const updatePropsWithHash: Partial<ToolModel> & { contentHash?: string } = updateProps;
        updatePropsWithHash.contentHash = computeToolContentHash(mergedForHash);

        const updateData = toDatabase(toEntityInstance(ToolEntity, updateProps));

        // Filter out protected fields (id, createdAt)
        // eslint-disable-next-line @typescript-eslint/no-unused-vars
        const { id: _id, created_at: _createdAt, ...filteredUpdateData } = updateData;

        if (Object.keys(filteredUpdateData).length === 0) {
          return await this.findById(id);
        }

        const result = await this.updateEntity<Record<string, unknown>>('tools', id, filteredUpdateData);
        return result ? fromDatabase(ToolEntity, result) : null;
      },
      'update',
      'Tool',
      id
    );
  }

  async updateStarship(toolId: string, starshipId: string): Promise<ToolModel> {
    return this.executeWithErrorHandling(
      async () => {
        const connection = this.getConnection();

        // Validate starshipId exists
        const starshipCheck = await connection.queryOne<{ count: string }>('SELECT COUNT(*) as count FROM starships WHERE id = $1', [
          starshipId,
        ]);

        if (!starshipCheck || parseInt(starshipCheck.count) === 0) {
          this.handleNotFound('Starship', starshipId);
        }

        // Update tool's starship assignment
        const result = await this.updateEntity<Record<string, unknown>>('tools', toolId, {
          starship_id: starshipId,
          updated_at: new Date().toISOString(),
        });

        if (!result) {
          this.handleNotFound('Tool', toolId);
        }

        return fromDatabase(ToolEntity, result);
      },
      'updateStarship',
      'Tool',
      toolId
    );
  }

  async delete(id: string): Promise<boolean> {
    return this.executeWithErrorHandling(
      async () => {
        // Delete will cascade to remove relationships via foreign key constraints
        return await this.deleteEntity('tools', id);
      },
      'delete',
      'Tool',
      id
    );
  }
}
